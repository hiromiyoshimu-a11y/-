import fs from 'fs';

function updatePapersFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
  const paper = data.papers.find(p => p.pmid === '42019791');
  if (paper) {
    paper.titleJa = '心内膜パルスフィールドアブレーション後の可逆的な心外膜近接場電気サイレンシング: 貫壁病変の耐久性への影響';
    paper.summaryJa = [
      '【概要】心内膜側からのパルスフィールドアブレーション (PFA) 施行直後に観察される心外膜側近接場電位の可逆的抑制 (電気的サイレンシング) と貫壁性病変耐久性の検証 (症例報告 (Case Report) / N = 1例)',
      '【方法】難治性壁内心室頻拍 (VT) 基質に対し、心内膜側 PFA 通電前後の心外膜三次元マッピングおよび電位・エレクトロポレーション反応を連続評価した',
      '【結果】心内膜 PFA 直後に心外膜電位の即時消失を認めたが、一定時間経過後に可逆的な電位回復が確認され、急性期の電位サイレンシングが必ずしも永続的な貫壁性壊死を意味しないことが判明した',
      '【結論】心内膜 PFA 後の急性期心外膜電位消失には可逆的エレクトロポレーション要素が含まれるため、貫壁性病変形成および長期耐久性の評価には慎重な経過観察が必要である'
    ].join('\n');

    paper.abstractJa = [
      '【背景】\n壁内（心筋深部）心室頻拍（VT）回路に対するカテーテルアブレーションは、従来の高周波（RF）エネルギーでは解剖学的深部への十分な貫壁性病変の形成が困難であるため重要な臨床課題となっている。不可逆的エレクトロポレーションを原理とするパルスフィールドアブレーション（PFA）は心筋深部への病変形成が期待されるが、急性期における電位消失が永続的な組織壊死（貫壁性病変）を意味するのか、可逆的なエレクトロポレーションによる一時的電位抑制なのかについては十分解明されていない。',
      '【方法】\n心筋深部・壁内 VT 回路を有する患者に対し、心内膜側からの PFA カテーテル通電を実施した。通電前後に心外膜側の高密度三次元電気解剖学的マッピングおよび近接場局所電位の経時的変化を精密に記録・解析した。',
      '【結果】\n心内膜側からの PFA 通電直後、対向する心外膜側の近接場電位は即座に完全に消失（電気的サイレンシング）した。しかし、その後の経過観察において、消失した心外膜電位が徐々に回復する「可逆的エレクトロポレーション（Reversible Electroporation）」現象が確認された。これにより、急性期の電位消失のみでは貫壁性病変の完成を過大評価する危険性があることが明らかとなった。',
      '【結論】\n心内膜 PFA 施行直後の心外膜側近接場電位の消失には可逆的な非致命的細胞膜損傷が含まれており、急性期の電位消失が必ずしも永続的な貫壁性解離・病変耐久性を保証するものではない。治療成功の判定および貫壁性の評価においては、十分な観察時間の確保と長期的な耐久性検証が不可欠である。'
    ].join('\n\n');

    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf-8');
    console.log(`Updated ${filePath}`);
  }
}

updatePapersFile('public/papers.json');
updatePapersFile('outputs/papers.json');
