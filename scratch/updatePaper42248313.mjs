import fs from 'fs';

function updatePapersFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  const data = JSON.parse(fs.readFileSync(filePath, 'utf-8'));
  const paper = data.papers.find(p => p.pmid === '42248313');
  if (paper) {
    paper.titleJa = '焦点パルスフィールドエネルギーを使用した Para-His 大動脈周囲 VT アブレーション';
    paper.summaryJa = [
      '【概要】ヒス束近傍・大動脈周囲の深部瘢痕に起因する心室頻拍 (VT) に対する焦点パルスフィールドアブレーション (PFA) の有用性と安全性の検証 (症例報告 (Case Report) / N = 1例)',
      '【方法】従来の高周波 (RF) アブレーションでは伝導系傷害のリスクが高い基質に対し、心筋選択性を有する焦点 PFA カテーテルを用いたマッピングおよびエネルギー照射を実施した',
      '【結果】房室伝導系への永続的傷害を回避しつつ、深部瘢痕由来の VT 標的電位を迅速かつ効果的に消失させ、急性期成功を達成した',
      '【結論】伝導系に隣接する Para-His 大動脈周囲 VT 基質において、焦点 PFA は安全かつ有効な新しいアブレーション治療選択肢となり得る'
    ].join('\n');

    paper.abstractJa = [
      '【背景】\n中隔流出領域（Para-His・大動脈周囲）から発生する心室頻拍（VT）のカテーテルアブレーションは、病変基質が深部に位置し瘢痕化している上、刺激伝導系に近接しているため極めて難易度が高い。従来のラジオ波（RF）アブレーションでは通電エンドポイントが不明瞭であり、房室ブロックなどの主要合併症リスクが高い。不可逆的エレクトロポレーションを利用したパルスフィールドアブレーション（PFA）は、心筋選択性が高く隣接組織への副損傷を抑えて深部病変を形成できる新しいエネルギー源として注目されている。',
      '【方法】\nヒス束・大動脈周囲の深部瘢痕に由来する難治性心室頻拍患者に対し、高密度三次元マッピングシステムおよび焦点型 PFA カテーテルを用いて心室内マッピングとアブレーションを実施した。局所電位の変化および伝導系への影響をモニタリングしながら PFA 通電プロトコルを行った。',
      '【結果】\n焦点 PFA 通電により、ヒス束近傍の危険領域においても伝導系（房室伝導・ヒス束電位）への永続的障害を生じさせることなく、目標とする VT の発生源および瘢痕部局所電位を迅速かつ完全に消失させ、急性期成功を達成した。',
      '【結論】\n伝導系に近接する Para-His 大動脈周囲の複雑な心室頻拍基質に対し、焦点 PFA は高い解剖学的選択性と治療効果を発揮し、従来のラジオ波アブレーションに代わる安全で有望なアプローチであることが示された。'
    ].join('\n\n');

    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf-8');
    console.log(`Updated ${filePath}`);
  }
}

updatePapersFile('public/papers.json');
updatePapersFile('outputs/papers.json');
